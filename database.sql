-- =============================================
-- POKÉDEX INTERACTIVA AVANZADA - Schema 2026
-- =============================================

CREATE DATABASE IF NOT EXISTS pokedex_2026;
USE pokedex_2026;

-- =============================================
-- TABLA: pokemon
-- =============================================
DROP TABLE IF EXISTS pokemon;
CREATE TABLE IF NOT EXISTS pokemon (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    tipo_principal VARCHAR(50) NOT NULL,
    tipo_secundario VARCHAR(50) DEFAULT NULL,
    nivel INT NOT NULL DEFAULT 10,
    ataque INT NOT NULL DEFAULT 50,
    defensa INT NOT NULL DEFAULT 50,
    velocidad INT NOT NULL DEFAULT 50,
    hp INT NOT NULL DEFAULT 45,
    imagen VARCHAR(500) DEFAULT NULL,
    is_favorite TINYINT(1) DEFAULT 0
);

-- =============================================
-- TABLA: usuarios (Login Google)
-- =============================================
CREATE TABLE IF NOT EXISTS usuarios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    foto VARCHAR(500) DEFAULT '',
    fecha_registro DATETIME DEFAULT NOW(),
    nivel_entrenador INT DEFAULT 1,
    victorias INT DEFAULT 0,
    derrotas INT DEFAULT 0,
    insignias JSON DEFAULT ('[]'),
    racha_actual INT DEFAULT 0
);

-- =============================================
-- TABLA: batallas
-- =============================================
CREATE TABLE IF NOT EXISTS batallas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    usuario_id INT DEFAULT NULL,
    pokemon1 VARCHAR(100) NOT NULL,
    pokemon2 VARCHAR(100) NOT NULL,
    ganador VARCHAR(100) NOT NULL,
    modo VARCHAR(20) DEFAULT 'pvp',
    fecha DATETIME DEFAULT NOW(),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

